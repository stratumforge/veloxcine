  function applySettingsObject(prof) {
    if (!prof) return;

    // Aspect Override
    if (prof.defaultAspect) {
      state.aspect.mode = prof.defaultAspect;
      state.aspect.enabled = prof.defaultAspect !== 'original';
    } else if (prof.aspectEnabled !== undefined) {
      state.aspect.enabled = Boolean(prof.aspectEnabled);
    }
    applyAspectTransform();

    // Subtitle Position & Modifier
    if (prof.subPosition) {
      state.subtitles.preset = prof.subPosition;
      state.subtitles.enabled = true;
      if (prof.subPosition === 'top-center') { state.subtitles.posX = 50; state.subtitles.posY = 12; }
      else if (prof.subPosition === 'bottom-center') { state.subtitles.posX = 50; state.subtitles.posY = 88; }
      else if (prof.subPosition === 'bottom-black-bar') { state.subtitles.posX = 50; state.subtitles.posY = 96; }
      else if (prof.subPosition === 'top-black-bar') { state.subtitles.posX = 50; state.subtitles.posY = 4; }
    } else if (prof.subEnabled !== undefined) {
      state.subtitles.enabled = Boolean(prof.subEnabled);
    }

    if (prof.brightness !== undefined) {
      state.subtitles.brightness = parseInt(prof.brightness, 10);
    }
    injectSubtitleStyles();

    if (prof.adWarpEnabled !== undefined) state.adWarp.enabled = prof.adWarpEnabled;
    if (prof.bingeEnabled !== undefined) {
      state.binge.autoSkipIntro = prof.bingeEnabled;
      state.binge.autoSkipRecap = prof.bingeEnabled;
    }
  }

  function resetAllSettingsToDefaults() {
    state.aspect.enabled = false;
    state.aspect.mode = 'original';
    const video = state.activeVideo || findPrimaryVideo();
    if (video) {
      state.activeVideo = video;
      video.style.transform = '';
      video.style.objectFit = '';
      video.style.transition = '';
      if (video.playbackRate && video.playbackRate !== 1.0) video.playbackRate = 1.0;
      if (video.muted) video.muted = false;
    }

    state.subtitles.enabled = false;
    state.subtitles.preset = 'bottom-center';
    state.subtitles.posX = 50;
    state.subtitles.posY = 88;
    state.subtitles.brightness = 100;

    state.subtitles.enabled = true;
    state.subtitles.preset = 'bottom-center';
    state.subtitles.posX = 50;
    state.subtitles.posY = 88;
    state.subtitles.brightness = 100;
    injectSubtitleStyles();

    document.querySelectorAll('.caption-window, .ytp-caption-window-bottom, .ytp-caption-window-rollup, .player-timedtext, .player-timedtext-text-container').forEach(el => {
      el.style.transform = '';
      el.style.left = '';
      el.style.top = '';
      el.style.bottom = '';
      el.style.right = '';
      el.style.margin = '';
      el.style.opacity = '';
      el.style.filter = '';
    });
    window.dispatchEvent(new Event('resize'));

    state.adWarp.enabled = true;
    state.binge.autoSkipIntro = true;
    state.binge.autoSkipRecap = true;
    state.youtube.autoTheater = false;
    state.youtube.hideShorts = false;

    showToast('↺ VeloxCine: Subtitles & Settings Reset to Defaults');
  }

  chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
    if (msg.action === 'RESET_SETTINGS') {
      resetAllSettingsToDefaults();
      sendResponse({ status: 'OK' });
    } else if (msg.action === 'APPLY_SETTINGS_NOW') {
      applySettingsObject(msg.settings);
      sendResponse({ status: 'OK' });
    } else if (msg.action === 'PING') {
      sendResponse({ status: 'OK', platform: state.detectedPlatform, videoBound: Boolean(state.activeVideo) });
    } else if (msg.action === 'CYCLE_ASPECT') {
      cycleAspectRatio();
      sendResponse({ mode: state.aspect.mode });
    } else if (msg.action === 'TOGGLE_DIMMER') {
      toggleDimmer();
      sendResponse({ brightness: state.subtitles.brightness });
    } else if (msg.action === 'TOGGLE_HUD') {
      showToast('VeloxCine: Controls are in Extension Toolbar Icon');
      sendResponse({ visible: false });
    }
    return true;
  });

  function showToast(text) {
    const toast = document.getElementById('velox-toast');
    const msg = document.getElementById('velox-toast-msg');
    if (!toast || !msg) return;
    msg.textContent = text;
    toast.classList.add('show');
    clearTimeout(toast._timer);
    toast._timer = setTimeout(() => {
      toast.classList.remove('show');
    }, 2800);
  }

  // Persistent Settings Loader
  async function loadPersistedSettings() {
    try {
      const data = await chrome.storage.local.get('veloxcine_settings');
      const settings = data.veloxcine_settings || {};
      const platform = state.detectedPlatform;
      // Merge global settings with platform-specific profile
      const prof = { ...(settings.global || {}), ...(platform !== 'generic' && settings.profiles?.[platform] ? settings.profiles[platform] : {}) };
      applySettingsObject(prof);
    } catch (e) {}
  }

  try {
    chrome.storage.onChanged.addListener((changes, area) => {
      if (area === 'local' && changes.veloxcine_settings) {
        loadPersistedSettings();
      }
    });
  } catch (e) {}

  async function init() {
    if (typeof VeloxLicense !== 'undefined' && VeloxLicense.init) {
      try {
        await VeloxLicense.init();
        state.isPremium = VeloxLicense.isPremium();
      } catch(e) {}
    }
    await loadPersistedSettings();
    injectYouTubeMainWorldBridge();
    createHUD();
    injectSubtitleStyles();
    setupDraggableAnchor();
    const v = findPrimaryVideo();
    if (v) bindVideo(v);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
